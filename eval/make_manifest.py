"""Write eval/manifest.jsonl for the staged images that exist under eval/data/images.
Owner: Carlos.

Split, destinations and the default categories come from SHOT_LIST.md, provenance from
provenance.json. When a label file exists, categories and destinations come from it,
because the label is what the image actually contains. Rerun after labeling.

Rows for other sources (webpii, hard negatives) already in the manifest are kept.

Usage: uv run python eval/make_manifest.py
"""

import json
from pathlib import Path

from check_shot_list import parse_rows
from schemas import Label, ManifestRow

EVAL = Path(__file__).parent
LICENSES = {
    "photo": "team photo, consenting participants",
    "synthetic": "synthetic, AI generated by the team, fake data",
}
ALL_DESTINATIONS = ["public", "team", "ai_assistant"]


def build_rows(image_ids: set[str], provenance: dict, labels: dict[str, Label]) -> list[ManifestRow]:
    rows = []
    for r in parse_rows():
        if r["id"] not in image_ids:
            continue
        label = labels.get(r["id"])
        if label:
            destinations = [d for d in ALL_DESTINATIONS if d in label.destinations]
            categories = sorted({f.category for fs in label.destinations.values() for f in fs})
        else:
            destinations = ALL_DESTINATIONS if r["triple"] else ["public"]
            categories = r["categories"]
        prov = provenance[r["id"]]
        rows.append(ManifestRow(
            image_id=r["id"], source="staged", license=LICENSES[prov], split=r["split"],
            provenance=prov, categories=categories, destinations_labeled=destinations,
        ))
    return rows


def main() -> None:
    images = {p.stem for p in (EVAL / "data" / "images").glob("s*.*")}
    provenance = json.loads((EVAL / "provenance.json").read_text())
    missing = sorted(i for i in images if i not in provenance)
    if missing:
        raise SystemExit(f"add provenance for {missing} to eval/provenance.json")
    labels = {p.stem: Label.model_validate_json(p.read_text()) for p in (EVAL / "labels").glob("*.json")}
    path = EVAL / "manifest.jsonl"
    old = [ManifestRow.model_validate_json(l) for l in path.read_text().splitlines() if l.strip()]
    new = build_rows(images, provenance, labels)
    keep = [r for r in old if r.image_id not in {n.image_id for n in new}]
    out = sorted(keep + new, key=lambda r: r.image_id)
    path.write_text("".join(r.model_dump_json() + "\n" for r in out))
    print(f"wrote {len(out)} rows ({sum(r.provenance == 'photo' for r in out)} photo, "
          f"{sum(r.provenance == 'synthetic' for r in out)} synthetic, "
          f"{sum(r.image_id in labels for r in out)} with labels)")


if __name__ == "__main__":
    main()
